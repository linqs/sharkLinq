#!/bin/bash

# Setup script for installing the cron job for shark_identification.py
# This script locates its checkout and sets up the cron job.

echo "Setting up cron job for shark_identification.py..."

# Resolve the checkout from this script (scripts/ under the checkout), independent of the invoking directory.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

echo "Detected project directory: $PROJECT_DIR"

# Check that the resolved checkout contains the scheduled entry point.
if [ ! -f "$PROJECT_DIR/scripts/shark_identification.py" ]; then
    echo "Error: shark_identification.py not found beside setup_cron.sh"
    exit 1
fi

# Cron runs with a bare PATH, so record the interpreter that has this checkout's dependencies.
if [ -z "${SHARK_PYTHON:-}" ]; then
    SHARK_PYTHON="$(python3 -c 'import sys; print(sys.executable)' 2>/dev/null)"
fi
if [ -n "$SHARK_PYTHON" ]; then
    echo "Using Python interpreter: $SHARK_PYTHON"
else
    echo "Warning: could not determine the Python interpreter; cron will use python3 from its PATH."
fi

# Generate the cron wrapper from the same self-locating convention each time.
WRAPPER_SCRIPT="$SCRIPT_DIR/cron_wrapper.sh"
cat > "$WRAPPER_SCRIPT" << 'EOF'
#!/bin/bash

# Wrapper script for cron job
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOG_FILE="$PROJECT_DIR/data-out/logs/cron_output.txt"

# Ensure directory exists
mkdir -p "$PROJECT_DIR/data-out/logs"

# Log the start
echo "$(date): Starting shark_identification.py snapshot" >> "$LOG_FILE"

# Run the script
cd "$PROJECT_DIR" || exit 1
"${SHARK_PYTHON:-python3}" -m scripts.shark_identification -s
exit_code=$?

# Log the result
if [ "$exit_code" -eq 0 ]; then
    echo "$(date): SUCCESS - shark_identification.py snapshot completed" >> "$LOG_FILE"
else
    echo "$(date): ERROR - shark_identification.py snapshot failed with exit code $exit_code" >> "$LOG_FILE"
fi

exit "$exit_code"
EOF
echo "Created or refreshed cron wrapper script: $WRAPPER_SCRIPT"

# Make the wrapper script executable
chmod +x "$WRAPPER_SCRIPT"

# Set up logging file for cron output
LOG_DIR="$PROJECT_DIR/data-out/logs"
CRON_LOG_FILE="$LOG_DIR/cron_output.txt"

# Create log directory if it doesn't exist
if [ ! -d "$LOG_DIR" ]; then
    mkdir -p "$LOG_DIR"
    echo "Created log directory: $LOG_DIR"
fi

# Create cron log file if it doesn't exist
if [ ! -f "$CRON_LOG_FILE" ]; then
    touch "$CRON_LOG_FILE"
    echo "$(date): Created cron log file: $CRON_LOG_FILE" >> "$CRON_LOG_FILE"
    echo "Created cron log file: $CRON_LOG_FILE"
fi

# Ask the operating system for unique temporary files and always clean them up.
TEMP_CRON_FILE="$(mktemp)"
EXISTING_CRON_FILE="$(mktemp)"
CRONTAB_ERROR_FILE="$(mktemp)"
trap 'rm -f "$TEMP_CRON_FILE" "$EXISTING_CRON_FILE" "$CRONTAB_ERROR_FILE"' EXIT

# Preserve unrelated cron entries. A missing crontab is safe to initialize, but
# any other read failure must abort rather than risk replacing unknown jobs.
if crontab -l > "$EXISTING_CRON_FILE" 2> "$CRONTAB_ERROR_FILE"; then
    :
elif [ ! -s "$EXISTING_CRON_FILE" ] && grep -qi "no crontab" "$CRONTAB_ERROR_FILE"; then
    : > "$EXISTING_CRON_FILE"
else
    echo "Error: unable to read the existing crontab; no changes were installed"
    if [ -s "$CRONTAB_ERROR_FILE" ]; then
        cat "$CRONTAB_ERROR_FILE" >&2
    fi
    exit 1
fi

CRON_BLOCK_BEGIN="# BEGIN shark-matcher-app snapshot"
CRON_BLOCK_END="# END shark-matcher-app snapshot"

# Remove this installer's prior managed block and legacy entries for this exact
# wrapper. Reject malformed markers rather than discarding uncertain content.
if ! awk \
    -v begin="$CRON_BLOCK_BEGIN" \
    -v end="$CRON_BLOCK_END" \
    -v wrapper="$WRAPPER_SCRIPT" \
    '
    $0 == begin {
        if (inside) {
            invalid = 1
        }
        inside = 1
        next
    }
    $0 == end {
        if (!inside) {
            invalid = 1
        }
        inside = 0
        next
    }
    inside {
        next
    }
    index($0, wrapper) > 0 {
        next
    }
    {
        print
    }
    END {
        if (inside || invalid) {
            exit 1
        }
    }
    ' "$EXISTING_CRON_FILE" > "$TEMP_CRON_FILE"; then
    echo "Error: existing shark-matcher-app cron markers are malformed"
    echo "No changes were installed; review the current crontab with: crontab -e"
    exit 1
fi

if [ -s "$TEMP_CRON_FILE" ]; then
    printf '\n' >> "$TEMP_CRON_FILE"
fi

{
    echo "$CRON_BLOCK_BEGIN"
    echo "# Store a snapshot of the database every week at 00:00 on Sunday."
    echo "# Auto-generated by setup_cron.sh on $(date)"
    echo "PATH=/usr/local/bin:/usr/bin:/bin"
    if [ -n "$SHARK_PYTHON" ]; then
        echo "SHARK_PYTHON=$SHARK_PYTHON"
    fi
    if [ -n "${SHARK_DATA_ROOT:-}" ]; then
        echo "SHARK_DATA_ROOT=$SHARK_DATA_ROOT"
    fi
    echo "0 0 * * 0 \"$WRAPPER_SCRIPT\""
    echo "$CRON_BLOCK_END"
} >> "$TEMP_CRON_FILE"

echo "Created temporary cron file: $TEMP_CRON_FILE"
echo "Cron job content:"
cat "$TEMP_CRON_FILE"

# Ask for confirmation
echo ""
read -p "Do you want to install this cron job? (y/N): " -n 1 -r
echo ""

if [[ $REPLY =~ ^[Yy]$ ]]; then
    # Install the cron job
    crontab "$TEMP_CRON_FILE"
    
    if [ $? -eq 0 ]; then
        echo "Cron job installed successfully!"
        echo "The database snapshot will run every Sunday at midnight."
        echo "Existing cron entries were preserved."
        echo ""
        echo "Logging enabled:"
        echo "   - Log file: $CRON_LOG_FILE"
        echo "   - Wrapper script: $WRAPPER_SCRIPT"
        echo "   - Logs execution time and success/failure status"
        echo "   - View logs with: tail -f $CRON_LOG_FILE"
        echo ""
        echo "To verify the cron job was installed, run: crontab -l"
        echo "To remove only this snapshot job, run: crontab -e"
        echo "Delete the cron_wrapper.sh entry and keep unrelated jobs."
    else
        echo "Error: failed to install cron job"
        exit 1
    fi
else
    echo "Cron job installation cancelled"
fi

echo ""
echo "Setup complete!"
